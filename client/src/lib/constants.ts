export interface AllocationBucket {
  label: string;
  pct: number;
  color: string;
  description: string;
  lockup: string;
  vesting?: { cliffMonths: number; vestMonths: number };
}

/**
 * Computes locked vs. unlocked MOON for a vested allocation bucket, mirroring
 * the on-chain VestingWalletCliff math (linear after the cliff). Returns null
 * for buckets with no vesting schedule. `nowMs` is injectable for testing.
 */
export function vestingStatus(bucket: AllocationBucket, nowMs: number = Date.now()) {
  if (!bucket.vesting) return null;
  const totalTokens = (TOKENOMICS.totalSupply * bucket.pct) / 100;
  const start = TOKENOMICS.vestingStart;
  const { cliffMonths, vestMonths } = bucket.vesting;

  // No anchor date yet, or vesting hasn't started: fully locked.
  if (!start) {
    return { unlockedPct: 0, lockedPct: 100, unlockedTokens: 0, lockedTokens: totalTokens, started: false };
  }
  const nowS = Math.floor(nowMs / 1000);
  const MONTH = 30 * 24 * 60 * 60;
  const cliffS = start + cliffMonths * MONTH;
  const endS = start + vestMonths * MONTH;

  let unlockedPct: number;
  if (nowS < cliffS) unlockedPct = 0;
  else if (nowS >= endS) unlockedPct = 100;
  else unlockedPct = ((nowS - start) / (endS - start)) * 100;

  const unlockedTokens = (totalTokens * unlockedPct) / 100;
  return {
    unlockedPct,
    lockedPct: 100 - unlockedPct,
    unlockedTokens,
    lockedTokens: totalTokens - unlockedTokens,
    started: nowS >= start,
  };
}

// Client-side mirror of server/oracle-model.ts for the interactive explorer.
const JACKPOT_ODDS_M = 292.2;
const TICKETS_PER_JACKPOT_M = 0.4;

export function referenceModel(jackpotM: number) {
  const safe = jackpotM > 0 ? jackpotM : 0;
  const oracleValue =
    safe <= 0 ? MOON_V2.baseValue : MOON_V2.baseValue * (safe / MOON_V2.resetJackpotM);
  const resetRisk =
    safe <= 0 ? 0 : Math.min(Math.max(1 - Math.exp(-(safe * TICKETS_PER_JACKPOT_M) / JACKPOT_ODDS_M), 0), 1);
  // Locked fair-value model: raw Oracle Value discounted by survival probability.
  const riskAdjustedValue = oracleValue * (1 - resetRisk);
  return { oracleValue, resetRisk, riskAdjustedValue };
}

export function formatUsd(n: number | null | undefined, dp = 2): string {
  if (n == null || !isFinite(n)) return "—";
  return `$${n.toLocaleString(undefined, {
    minimumFractionDigits: dp,
    maximumFractionDigits: dp,
  })}`;
}

export function formatPct(frac: number | null | undefined, dp = 1): string {
  if (frac == null || !isFinite(frac)) return "—";
  return `${(frac * 100).toFixed(dp)}%`;
}

